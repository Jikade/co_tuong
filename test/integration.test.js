import test from 'node:test';
import assert from 'node:assert/strict';
import { mkdtemp, rm } from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';
import { once } from 'node:events';
import { createGameServer } from '../server.js';
import { createMemoryPersistence } from '../src/persistence/memory-persistence.js';
import { createFilePersistence } from '../src/persistence/file-persistence.js';
import { api, client, register, playAuthenticatedGame } from './helpers/authenticated-game.js';

test('two authenticated players capture, synchronize, reconnect, restart and replay using durable file storage', async (t) => {
  const directory = await mkdtemp(path.join(os.tmpdir(), 'cotuong-integration-'));
  const create = () => createFilePersistence(path.join(directory, 'state.json'));
  const { base, matchId } = await playAuthenticatedGame(t, create(), { restartPersistence: create });
  const outsider = await register(base, 'outsider');
  assert.equal((await api(base, `/api/matches/${matchId}`, { cookie: outsider.cookie })).status, 403);
  assert.equal((await api(base, '/api/history?playerId=forged', { cookie: outsider.cookie })).body.matches.length, 0);
  t.after(() => rm(directory, { recursive: true, force: true }));
});

test('expired sessions cannot open HTTP or WebSocket game access', async (t) => {
  let stamp = Date.now();
  const server = createGameServer({ host: '127.0.0.1', port: 0, persistence: createMemoryPersistence(), accountOptions: { sessionDays: 1, now: () => stamp } });
  const url = await server.listen(), base = url.replace('ws:', 'http:').replace('/ws', '');
  t.after(() => server.close());
  const a = await register(base, 'expired');
  stamp += 86400001;
  assert.equal((await api(base, '/api/me', { cookie: a.cookie })).status, 401);
  await assert.rejects(client(url, a.cookie), /401/);
});

test('accounts validate inputs, protect HTTP/WebSocket identity, revoke sessions, and reset passwords once', async (t) => {
  const deliveries = [];
  const persistence = createMemoryPersistence();
  const server = createGameServer({ host: '127.0.0.1', port: 0, persistence, accountOptions: { deliverReset: (d) => deliveries.push(d) } });
  const url = await server.listen(), base = url.replace('ws:', 'http:').replace('/ws', '');
  const sockets = [];
  t.after(async () => { await Promise.all(sockets.map((s) => s.close())); await server.close(); });
  assert.equal((await api(base, '/api/me')).status, 401);
  await assert.rejects(client(url), /401/);
  assert.equal((await api(base, '/api/auth/register', { method: 'POST', body: { username: 'ab', password: 'x' } })).status, 400);
  const a = await register(base, 'security');
  const duplicate = await api(base, '/api/auth/register', { method: 'POST', body: a });
  assert.equal(duplicate.status, 409);
  assert.equal((await api(base, '/api/auth/login', { method: 'POST', body: { username: a.username, password: 'Wrong123' } })).status, 401);
  assert.equal((await api(base, '/api/auth/logout', { cookie: a.cookie, method: 'POST', headers: { Origin: 'https://evil.example' } })).status, 403);
  const ca = await client(url, a.cookie); sockets.push(ca);
  ca.send({ action: 'create-room', playerId: 'forged-account-id', displayName: 'Forged', roomName: 'Fake' });
  await ca.next((m) => m.type === 'error');
  assert.equal(server.rooms.size, 0);
  ca.send({ action: 'create-room', roomName: 'Valid' });
  const state = await ca.next((m) => m.type === 'room-state');
  assert.equal(state.room.host.id, a.user.id);
  assert.equal(state.room.host.name, a.displayName);
  const otherSession = await api(base, '/api/auth/login', { method: 'POST', body: a });
  const sessions = await api(base, '/api/auth/sessions', { cookie: a.cookie });
  assert.equal(sessions.body.sessions.length, 2);
  const second = sessions.body.sessions.find((s) => !s.current);
  await api(base, `/api/auth/sessions/${second.id}`, { cookie: a.cookie, method: 'DELETE' });
  assert.equal((await api(base, '/api/me', { cookie: otherSession.cookie.split(';')[0] })).status, 401);
  await api(base, '/api/auth/forgot-password', { method: 'POST', body: { email: a.email } });
  assert.equal(deliveries.length, 1);
  const closed = once(ca.socket, 'close');
  const reset = { token: deliveries[0].token, password: 'Changed123', confirmPassword: 'Changed123' };
  assert.equal((await api(base, '/api/auth/reset-password', { method: 'POST', body: reset })).status, 200);
  await closed;
  assert.equal((await api(base, '/api/me', { cookie: a.cookie })).status, 401);
  assert.equal((await api(base, '/api/auth/reset-password', { method: 'POST', body: reset })).status, 400);
  assert.equal((await api(base, '/api/auth/login', { method: 'POST', body: a })).status, 401);
  assert.equal((await api(base, '/api/auth/login', { method: 'POST', body: { username: a.username, password: 'Changed123' } })).status, 200);
  const stored = await persistence.accounts.load();
  assert.match(stored.users[0].passwordHash, /^scrypt\$/);
  assert.equal(JSON.stringify(stored).includes(a.password), false);
});

test('friends, notifications, online room invitations, private rooms and logout share the same account identity', async (t) => {
  const server = createGameServer({ host: '127.0.0.1', port: 0, persistence: createMemoryPersistence() });
  const url = await server.listen(), base = url.replace('ws:', 'http:').replace('/ws', '');
  const sockets = [];
  t.after(async () => { await Promise.all(sockets.map((s) => s.close())); await server.close(); });
  const a = await register(base, 'friend_a'), b = await register(base, 'friend_b');
  const ca = await client(url, a.cookie), cb = await client(url, b.cookie); sockets.push(ca, cb);
  const search = await api(base, `/api/friends/search?q=${b.username}`, { cookie: a.cookie });
  assert.equal(search.body.users[0].id, b.user.id);
  const request = await api(base, '/api/friends/requests', { cookie: a.cookie, method: 'POST', body: { userId: b.user.id } });
  const duplicate = await api(base, '/api/friends/requests', { cookie: b.cookie, method: 'POST', body: { userId: a.user.id } });
  assert.equal(duplicate.body.id, request.body.id);
  assert.equal((await api(base, `/api/friends/requests/${request.body.id}/accept`, { cookie: a.cookie, method: 'POST' })).status, 404);
  assert.equal((await api(base, `/api/friends/requests/${request.body.id}/accept`, { cookie: b.cookie, method: 'POST' })).status, 200);
  const social = await api(base, '/api/friends', { cookie: a.cookie });
  assert.equal(social.body.friends[0].online, true);
  ca.send({ action: 'create-room', roomName: 'Private room', visibility: 'private' });
  const room = (await ca.next((m) => m.type === 'room-state')).room;
  assert.equal((await api(base, '/api/rooms/public', { cookie: b.cookie })).body.rooms.length, 0);
  const invite = await api(base, `/api/rooms/${room.code}/invites`, { cookie: a.cookie, method: 'POST', body: { userId: b.user.id } });
  assert.equal(invite.status, 200);
  const accepted = await api(base, `/api/rooms/invites/${invite.body.id}/accept`, { cookie: b.cookie, method: 'POST' });
  assert.equal(accepted.body.roomCode, room.code);
  cb.send({ action: 'join-room', roomCode: accepted.body.roomCode });
  await cb.next((m) => m.type === 'room-state' && m.room.opponent?.id === b.user.id);
  assert.ok((await api(base, '/api/notifications', { cookie: b.cookie })).body.notifications.length > 0);
  const closed = once(cb.socket, 'close');
  await api(base, '/api/auth/logout', { cookie: b.cookie, method: 'POST' });
  await closed;
  assert.equal((await api(base, '/api/me', { cookie: b.cookie })).status, 401);
});
